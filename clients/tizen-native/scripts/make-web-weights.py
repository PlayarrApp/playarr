#!/usr/bin/env python3
"""Generates what NUI needs to draw the web's variable-weight Nunito Sans: web CSS uses weights such as 560, 640, 860; NUI only picks the
named ones. From web DOM dumps (scripts/parity capture dumps, JSON lists with a "font" field "<weight> <size>px/..") this writes
  src/Playarr.Tizen/WebWeights.cs   size -> web weights used at that size (Ui.Face picks the nearest to the weight a call site asks for)
  src/Playarr.Tizen/res/fonts/NunitoSansW<weight>.ttf   static instances of docs/parity/fonts/NunitoSans-wght-web.ttf, family "Nunito Sans W<weight>"
Usage: make-web-weights.py <dir with dump json files> (needs fonttools)"""
import sys, json, glob, pathlib, collections
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
root = pathlib.Path(__file__).resolve().parents[3]
src = root / "docs/parity/fonts/NunitoSans-wght-web.ttf"
res = root / "clients/tizen-native/src/Playarr.Tizen"
by_size = collections.defaultdict(set)
for f in glob.glob(sys.argv[1] + "/*.json"):
    for e in json.load(open(f)):
        if e.get("font") and "JetBrains" not in e["font"]:
            w, rest = e["font"].split(" ", 1)
            by_size[round(float(rest.split("/")[0].replace("px", "")), 3)].add(int(w))
named = {300, 400, 500, 600, 700, 800}
weights = sorted({w for ws in by_size.values() for w in ws} - named)
rows = ",\n".join(f"        [{s}f] = [{', '.join(map(str, sorted(ws)))}]" for s, ws in sorted(by_size.items()))
(res / "WebWeights.cs").write_text(f"""namespace Playarr.Tizen;

// Generated by scripts/make-web-weights.py from web DOM dumps: the font weights web CSS uses at each font size.
internal static class WebWeights
{{
    public static readonly Dictionary<float, int[]> BySize = new()
    {{
{rows}
    }};

    public static readonly int[] Instanced = [{', '.join(map(str, weights))}];
}}
""")
for w in weights:
    f = instancer.instantiateVariableFont(TTFont(src), {"wght": w})
    fam = f"Nunito Sans W{w}"
    for n in list(f["name"].names):
        if n.nameID in (16, 17, 21, 22, 25): f["name"].removeNames(nameID=n.nameID)
    for pid, eid, lid in ((3, 1, 0x409), (1, 0, 0)):
        f["name"].setName(fam, 1, pid, eid, lid); f["name"].setName("Regular", 2, pid, eid, lid)
        f["name"].setName(fam, 4, pid, eid, lid); f["name"].setName(fam.replace(" ", "") + "-Regular", 6, pid, eid, lid)
    f["OS/2"].usWeightClass = 400
    f.save(res / "res/fonts" / f"NunitoSansW{w}.ttf")
print(len(weights), "instances", weights)
