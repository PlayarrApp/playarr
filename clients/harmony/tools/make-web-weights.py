#!/usr/bin/env python3
"""Generates entry/src/main/ets/core/WebWeights.ts: the font weights web CSS uses at each font size, from the web layout refs
(<legend root>/<ref dir>/web/layout/<theme>/<screen>.json). `nunitoAt(weight, size)` picks the web weight nearest to the weight
a call site asks for. Usage: make-web-weights.py <legend root> <ref dir> [<ref dir> ...]"""
import glob, json, sys, collections, os
root, dirs = sys.argv[1], sys.argv[2:]
by = collections.defaultdict(set)
for d in dirs:
    for f in glob.glob(f"{root}/{d}/web/layout/*/*.json"):
        for e in json.load(open(f))["elements"]:
            if e.get("fontSize") and e.get("fontWeight") and e["text"] and "JetBrains" not in str(e):
                by[round(e["fontSize"], 2)].add(int(e["fontWeight"]))
sizes = ", ".join(str(s) for s in sorted(by))
rows = ",\n".join(f"  [{', '.join(map(str, sorted(by[s])))}]" for s in sorted(by))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "entry", "src", "main", "ets", "core", "WebWeights.ts")
open(out, "w").write(f"""// Generated by tools/make-web-weights.py from the web layout refs: the font weights web CSS uses at each font size.
export const WEB_SIZES: number[] = [{sizes}];
export const WEB_WEIGHTS: number[][] = [
{rows}
];
""")
print(len(by), "sizes")
