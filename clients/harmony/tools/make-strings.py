#!/usr/bin/env python3
"""Regenerate entry/src/main/ets/core/Strings.ts from the web's translation tables.

The web (clients/tv-web/web/src/lib/i18n/translations/{en,th,ja}.ts) is the source of truth. Only the key
prefixes the Harmony navigation and Settings screens show are copied, so the table stays small (same scope rule as
clients/xbox/tools/make-strings.py). Usage: python3 clients/harmony/tools/make-strings.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tv-web/web/src/lib/i18n/translations"
OUT = ROOT / "harmony/entry/src/main/ets/core/Strings.ts"
PREFIXES = (
    "settings.index.", "settings.language.", "settings.appearance.", "shell.nav.",
    "pages.home.customise.title", "pages.library.size",
)
ENTRY = re.compile(r'^  "([A-Za-z0-9_.]+)":\s*("(?:[^"\\]|\\.)*")\s*,?\s*$', re.M | re.S)


def load(lang):
    text = (SRC / f"{lang}.ts").read_text(encoding="utf-8")
    return {k: json.loads(v) for k, v in ENTRY.findall(text) if k.startswith(PREFIXES)}


tables = {lang: load(lang) for lang in ("en", "th", "ja")}
missing = [(lang, k) for lang in ("th", "ja") for k in tables["en"] if k not in tables[lang]]
if missing:
    sys.exit(f"keys missing from a translation: {missing[:5]}")
lines = [
    "// Generated by tools/make-strings.py from the web translation tables; do not edit by hand.",
    "export const STRINGS: Record<string, Record<string, string>> = {",
]
for lang, table in tables.items():
    lines.append(f"  {lang}: {{")
    for key in sorted(table):
        lines.append(f"    {json.dumps(key)}: {json.dumps(table[key], ensure_ascii=True)},")
    lines.append("  },")
lines += ["};", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(tables['en'])} keys x 3 languages -> {OUT.relative_to(ROOT.parent)}")
