#!/usr/bin/env python3
"""Regenerate src/Playarr.Core/Localization/Strings.g.cs from the web's translation tables.

The web (clients/tv-web/web/src/lib/i18n/translations/{en,th,ja}.ts) is the source of truth. Only the key
prefixes the Xbox Settings and navigation screens show are copied, so the table stays small.
Usage: python3 clients/xbox/tools/make-strings.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tv-web/web/src/lib/i18n/translations"
OUT = ROOT / "xbox/src/Playarr.Core/Localization/Strings.g.cs"
PREFIXES = (
    "settings.index.", "settings.language.", "settings.invite.", "settings.yourData.",
    "settings.appearance.", "settings.sectionLayout.", "shell.nav.", "remote.", "components.languageDropdown.", "pages.home.customise.title", "pages.library.size",
)
ENTRY = re.compile(r'^  "([A-Za-z0-9_.]+)":\s*("(?:[^"\\]|\\.)*")\s*,?\s*$', re.M | re.S)


def load(lang):
    text = (SRC / f"{lang}.ts").read_text(encoding="utf-8")
    table = {}
    for key, literal in ENTRY.findall(text):
        if key.startswith(PREFIXES):
            table[key] = json.loads(literal)
    return table


def cs(value):
    return json.dumps(value, ensure_ascii=True)  # C# understands \uXXXX escapes, and the file stays ASCII


tables = {lang: load(lang) for lang in ("en", "th", "ja")}
missing = [(lang, k) for lang in ("th", "ja") for k in tables["en"] if k not in tables[lang]]
if missing:
    sys.exit(f"keys missing from a translation: {missing[:5]}")
lines = [
    "// <auto-generated> by tools/make-strings.py from the web translation tables; do not edit by hand. </auto-generated>",
    "using System.Collections.Generic;",
    "",
    "namespace Playarr.Core.Localization",
    "{",
    "    public static class Strings",
    "    {",
    "        public static readonly Dictionary<string, Dictionary<string, string>> All = new Dictionary<string, Dictionary<string, string>>",
    "        {",
]
for lang, table in tables.items():
    lines.append(f'            ["{lang}"] = new Dictionary<string, string>')
    lines.append("            {")
    for key in sorted(table):
        lines.append(f"                [{cs(key)}] = {cs(table[key])},")
    lines.append("            },")
lines += ["        };", "    }", "}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(tables['en'])} keys x 3 languages -> {OUT.relative_to(ROOT.parent)}")
